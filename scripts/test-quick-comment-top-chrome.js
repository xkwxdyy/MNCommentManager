const assert = require('node:assert/strict');
const { fixture } = require('./test-quick-comment-keyboard');
const s = fixture();
const sessionId = s.api.getState(s.controller).sessionId;
const runtime = s.context.MNUtil;
runtime.currentWindow = s.addon.window; runtime.immersiveMode = true;
let capsuleRect = { x: 180, y: 20, width: 600, height: 50 };
const capsule = { window: s.addon.window, superview: s.addon.window, bounds: { x: 0, y: 0, width: 600, height: 50 }, convertRectToView: () => capsuleRect };
runtime.immersiveNavCapsuleView = capsule;
Object.defineProperty(s.controller.view, 'bounds', { configurable: true, get() { const frame = this.frame; return { x: 0, y: 0, width: frame.width, height: frame.height }; } });
s.controller.view.convertRectFromView = rect => ({ ...rect, y: rect.y - s.controller.view.frame.y });
s.context.Application.sharedInstance().studyController().notebookController.mindmapView.convertRectToView = rect => ({ ...rect, y: rect.y - s.controller.view.frame.y });
s.api.layout(s.controller);
assert.deepEqual(JSON.parse(JSON.stringify(s.controller.view.frame)), { x: 0, y: 78, width: 900, height: 522 });
assert.equal(s.controller.webView.frame.height, 522, 'WebView must share the reduced Native frame');
assert.equal(s.api.getState(s.controller).targetRect.y, 2, 'flight destination must be local to the reduced input viewport');
assert.equal(s.api.getState(s.controller).nativeViewport.height, 522);
s.api.present(s.controller);
s.api.updateDraft(s.controller, { sessionId: sessionId, text: '组词完成的草稿', draftRevision: 1, markdown: true });
capsuleRect = { ...capsuleRect, height: 80 }; s.api.layout(s.controller);
assert.equal(s.controller.view.frame.y, 108);
assert.equal(s.api.getState(s.controller).draft, '组词完成的草稿');
const keyboardShow = { UIKeyboardFrameEndUserInfoKey: { x: 0, y: 500, width: 900, height: 200 } };
const keyboardHide = { UIKeyboardFrameBeginUserInfoKey: { x: 0, y: 500, width: 900, height: 200 }, UIKeyboardFrameEndUserInfoKey: { x: 0, y: 700, width: 900, height: 200 }, UIKeyboardAnimationDurationUserInfoKey: 0.4, UIKeyboardAnimationCurveUserInfoKey: 7 };
s.notify('WillShow', keyboardShow); s.notify('WillHide', keyboardHide);
const event = s.lastEvent(); assert.equal(event.type, 'hide');
s.api.requestClose(s.controller, { sessionId: sessionId, reason: 'keyboard', eventId: event.eventId, text: '组词完成的草稿', draftRevision: 1, markdown: true });
assert.equal(s.controller.webView.transform.ty, 200, 'keyboard displacement must remain correct after viewport offset');
const frozen = s.controller.view.frame;
capsuleRect = { ...capsuleRect, height: 100 }; s.api.layout(s.controller);
assert.equal(s.controller.view.frame, frozen, 'closing geometry must remain frozen');
while (s.timers.length) s.timers.shift()();
const next = s.open();
assert.equal(next.view.frame.y, 128);
assert.equal(s.api.getState(next).draft, '组词完成的草稿');
assert.equal(s.a.comments.length, 1, 'layout and keyboard closing must not append a comment');
console.log('quick comment top chrome and keyboard tests passed');
