import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = new URL('../', import.meta.url);
const source = readFileSync(new URL('web/src/lib/commentMoveGesture.mjs', root), 'utf8');
const names = Array.from(source.matchAll(/^export (?:function|const) (\w+)/gm), match => match[1]);
const generated = '// Generated by scripts/sync-comment-move-gesture.mjs. Edit web/src/lib/commentMoveGesture.mjs.\n'
  + 'var __MN_COMMENT_MOVE_GESTURE_MNCommentManagerAddon = (function () {\n'
  + source.replace(/^export /gm, '')
  + '\nreturn { ' + names.join(', ') + ' };\n})();\n';
const target = new URL('src/CommentMoveGesture.js', root);
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== generated) throw new Error('CommentMoveGesture.js needs regeneration');
} else writeFileSync(fileURLToPath(target), generated);
