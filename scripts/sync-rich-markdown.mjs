import { build } from 'vite';
import fs from 'node:fs/promises';
import path from 'node:path';
import os from 'node:os';
import { fileURLToPath } from 'node:url';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const temp = await fs.mkdtemp(path.join(os.tmpdir(), 'mncm-md-'));
try {
  await build({
    configFile: false,
    root,
    logLevel: 'error',
    build: {
      outDir: temp,
      emptyOutDir: true,
      minify: true,
      lib: {
        entry: path.join(root, 'web/src/lib/markdownPlainText.mjs'),
        name: '__MN_COMMENT_MARKDOWN_MNCommentManagerAddon__',
        formats: ['iife'],
        fileName: () => 'CommentMarkdown.js',
      },
    },
  });
  const content =
    '// Generated by scripts/sync-rich-markdown.mjs from the shared Markdown converter.\n' +
    (await fs.readFile(path.join(temp, 'CommentMarkdown.js'), 'utf8'));
  const target = path.join(root, 'src/CommentMarkdown.js');
  if (process.argv.includes('--check')) {
    if ((await fs.readFile(target, 'utf8')) !== content)
      throw Error('Run node scripts/sync-rich-markdown.mjs');
  } else await fs.writeFile(target, content);
} finally {
  await fs.rm(temp, { recursive: true, force: true });
}
