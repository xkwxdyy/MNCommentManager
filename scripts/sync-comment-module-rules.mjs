import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
const root = new URL('../', import.meta.url);
const source = readFileSync(new URL('web/src/lib/commentModules.mjs', root), 'utf8');
const names = Array.from(source.matchAll(/export (?:function|const) (\w+)/g), m => m[1]);
const generated = '// Generated by scripts/sync-comment-module-rules.mjs. Edit web/src/lib/commentModules.mjs.\nvar __MN_COMMENT_MODULE_RULES__ = (function () {\n' + source.replace(/export /g, '') + '\nreturn { ' + names.join(', ') + ' };\n})();\n';
const target = new URL('src/CommentModuleRules.js', root);
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== generated) throw new Error('CommentModuleRules.js needs regeneration');
} else writeFileSync(fileURLToPath(target), generated);
