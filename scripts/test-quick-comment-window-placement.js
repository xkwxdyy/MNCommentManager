const assert = require('node:assert/strict');
const { setup } = require('./test-quick-comment');
const s = setup();
s.api.dispose(s.addon); s.timers.length = 0;
const branch = { alpha: 1 }, overlay = { alpha: 1 };
const window = s.addon.window;
window.bounds = { x: 0, y: 0, width: 1200, height: 900 };
window.subviews = [branch, overlay];
branch.superview = window;
s.studyView.superview = branch;
s.studyView.convertRectToView = () => ({ x: 40, y: 70, width: 1000, height: 700 });
window.insertSubviewAboveSubview = (view, anchor) => {
  window.subviews = window.subviews.filter(child => child !== view);
  window.subviews.splice(window.subviews.indexOf(anchor) + 1, 0, view);
  view.superview = window;
};
s.studyView.addSubview = view => { view.superview = s.studyView; };
const controller = s.open();
assert.equal(controller.view.superview, window, 'input must escape the study content hierarchy');
assert.deepEqual(window.subviews, [branch, controller.view, overlay], 'host window overlays must retain their order');
assert.deepEqual(controller.view.frame, { x: 40, y: 70, width: 1000, height: 700 });
s.api.present(controller);
branch.alpha = 0.1;
assert.equal(controller.view.alpha, 1, 'content branch dimming must not dim the input');
s.open();
assert.deepEqual(window.subviews, [branch, controller.view, overlay]);
s.studyView.convertRectToView = () => ({ x: 70, y: 30, width: 700, height: 500 });
s.api.layout(controller);
assert.deepEqual(controller.view.frame, { x: 70, y: 30, width: 700, height: 500 });
s.api.requestClose(controller, { sessionId: s.api.getState(controller).sessionId });
assert.equal(controller.view.alpha, 0, 'intentional exit fade must still run');
assert.equal(branch.alpha, 0.1, 'input must never reset host transparency');
assert.equal(overlay.alpha, 1);
console.log('quick comment window placement tests passed');
